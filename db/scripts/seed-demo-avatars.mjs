#!/usr/bin/env node
// Give every human member of the "پیشرو داده" demo organisation a profile
// picture, so rosters, attendee stacks and the account menu are not a wall of
// initials during the demo.
//
//   node scripts/seed-demo-avatars.mjs
//   node scripts/seed-demo-avatars.mjs --size 224     # square px, default 224
//   node scripts/seed-demo-avatars.mjs --force        # overwrite a real photo
//   node scripts/seed-demo-avatars.mjs --reset        # back to initials (null)
//
// The pictures are GENERATED HERE, not fetched: a drawn portrait — head, hair,
// eyes, shoulders, sometimes glasses or a beard — encoded as a PNG by this file
// (zlib is the only thing it needs; the repo has no image library, and adding
// one for a demo fixture is not worth the dependency). A face downloaded from a
// stock service would also be a real person's likeness standing in for a fake
// one, which is not a thing to seed a demo with.
//
// They are stored as `data:image/png;base64,…` because that is the only shape
// `echo.app_user.avatar_url` accepts (core/src/api/members.ts): an https URL
// is refused on purpose, since the product would then render an image it does
// not hold from an origin the uploader picked. The API's 131072-character cap
// is checked here too, so a seeded row can never be one the API would reject.
//
// Idempotent: the image is a pure function of the person's name, so re-running
// writes the same bytes. Without --force it leaves alone any avatar that is
// already set and was NOT generated by this script (an uploaded photo wins).
//
// THIS IS A SCRIPT AND MUST NEVER BECOME A MIGRATION (see seed-dev.mjs).
// Reads DATABASE_URL (the owner connection) from the environment, or from
// ../.env.dev when that file exists. Never prints a secret.

import { readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { deflateSync } from 'node:zlib'
import pg from 'pg'

const here = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const flag = (name, dflt) => {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : dflt
}
const RESET = args.includes('--reset')
const FORCE = args.includes('--force')
const SIZE = Number(flag('--size', '224'))
const ORG = 'de000000-0000-4000-8000-000000000001' // پیشرو داده
const MAX_URL_CHARS = 131072 // the API's own cap (members.ts)

if (!Number.isInteger(SIZE) || SIZE < 96 || SIZE > 512) {
  console.error('--size must be a whole number of pixels between 96 and 512')
  process.exit(2)
}

// ── PNG (truecolour, 8-bit, no interlace) ─────────────────────────────────
const CRC_TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()
const crc32 = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}
/** `rgb` is width*height*3 bytes, row-major. */
function encodePng(rgb, width, height) {
  const stride = width * 3
  // filter 1 (Sub) on every row: the image is a horizontal-ish gradient, so
  // each pixel is close to the one on its left and the residuals are tiny.
  const raw = Buffer.alloc((stride + 1) * height)
  for (let y = 0; y < height; y++) {
    const o = y * (stride + 1)
    raw[o] = 1
    for (let x = 0; x < stride; x++) {
      const left = x >= 3 ? rgb[y * stride + x - 3] : 0
      raw[o + 1 + x] = (rgb[y * stride + x] - left) & 0xff
    }
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 2 // colour type: truecolour
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ])
}

// ── colour ────────────────────────────────────────────────────────────────
const hash = (s) => {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619) >>> 0
  }
  return h
}
function hslToRgb(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1))
  const m = l - c / 2
  const [r, g, b] =
    h < 60 ? [c, x, 0]
    : h < 120 ? [x, c, 0]
    : h < 180 ? [0, c, x]
    : h < 240 ? [0, x, c]
    : h < 300 ? [x, 0, c]
    : [c, 0, x]
  return [Math.round((r + m) * 255), Math.round((g + m) * 255), Math.round((b + m) * 255)]
}

/*
 * ── the portrait ───────────────────────────────────────────────────
 *
 * A DRAWN PERSON, not a coloured tile with initials on it (2026-09-08: the
 * seeded people needed pictures of their own). The first version of this
 * script put the person's initials on a gradient, which is what `<Avatar>`
 * already draws when there is no picture — so every seeded row was a more
 * colourful way of showing exactly the thing a photo is supposed to replace.
 *
 * Flat vector shapes, evaluated per pixel: shoulders, a neck, a head, a
 * hairstyle, eyes, brows, a mouth, and sometimes glasses or a beard. Every
 * choice — skin tone, hair colour and cut, shirt hue, whether they wear
 * glasses — is a pure function of the person's email, so re-running writes the
 * same bytes and the same colleague keeps the same face.
 *
 * Drawn here rather than fetched, for the reason the header gives: the repo
 * has no image library, `avatar_url` takes only a `data:` PNG, and a face
 * downloaded from a stock service is a real person's likeness standing in for
 * a fake one.
 *
 * SUPERSAMPLED 3x3 rather than blurred: the edges that matter are the curve of
 * a head and the rim of a pair of glasses, and a box blur over a mask softens
 * the whole drawing in order to soften those.
 */
const SKIN = ['#f4d5bb', '#e8c0a0', '#dcac86', '#c68e63', '#a97047', '#7f5233']
const HAIR = ['#241a13', '#3d2b1c', '#6b4423', '#a9762f', '#8d8078', '#141312']
const SS = 3 // supersampling, per axis

/** a deterministic little PRNG, so each trait draws from its own stream */
function traits(seed) {
  let s = hash(seed) || 1
  const next = (n) => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0
    return s % n
  }
  const skin = SKIN[next(SKIN.length)]
  /* A HAIR COLOUR THE SKIN CAN BE TOLD FROM. The first draft picked the two
     independently and produced a dark-brown head on dark-brown skin — a
     silhouette with eyes in it. Step through the list until the two are at
     least 45 apart in luminance; the list is ordered dark-to-light with a grey
     in it, so this always terminates. */
  const lum = (h) => 0.299 * parseInt(h.slice(1, 3), 16)
                   + 0.587 * parseInt(h.slice(3, 5), 16)
                   + 0.114 * parseInt(h.slice(5, 7), 16)
  let hi = next(HAIR.length)
  for (let i = 0; i < HAIR.length && Math.abs(lum(HAIR[hi]) - lum(skin)) < 45; i++) {
    hi = (hi + 1) % HAIR.length
  }
  return {
    skin,
    hair: HAIR[hi],
    /** 0 short · 1 long · 2 bun · 3 close-cropped */
    cut: next(4),
    hue: next(360),
    glasses: next(5) < 2,
    beard: next(5) < 2,
  }
}

const hex = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]
const shade = (rgb, f) => rgb.map((c) => Math.max(0, Math.min(255, Math.round(c * f))))
const inEllipse = (x, y, cx, cy, rx, ry) => {
  const dx = (x - cx) / rx
  const dy = (y - cy) / ry
  return dx * dx + dy * dy <= 1
}

function avatarPng(_name, seed, size) {
  const t = traits(seed)
  const skin = hex(t.skin)
  const hair = hex(t.hair)
  const shirt = hslToRgb(t.hue, 0.42, 0.44)
  const bgTop = hslToRgb((t.hue + 180) % 360, 0.34, 0.86)
  const bgBottom = hslToRgb((t.hue + 200) % 360, 0.30, 0.74)
  const ink = shade(skin, 0.26)

  /* the whole drawing in UNIT coordinates (0..1 across the square), so --size
     changes the resolution and nothing else about the picture */
  const paint = (x, y) => {
    let c = bgTop.map((v, i) => v + (bgBottom[i] - v) * y)

    // shoulders, then the neck in front of them
    if (inEllipse(x, y, 0.5, 1.06, 0.44, 0.34)) c = shirt
    if (x > 0.435 && x < 0.565 && y > 0.58 && y < 0.80) c = shade(skin, 0.86)

    const onHead = inEllipse(x, y, 0.5, 0.44, 0.215, 0.26)
    // ears first, so the hair below can cover them
    if (inEllipse(x, y, 0.285, 0.47, 0.032, 0.045) || inEllipse(x, y, 0.715, 0.47, 0.032, 0.045)) c = skin
    if (onHead) c = skin

    /* HAIR IS A HAIRLINE, not a hood. The first draft kept the band all the
       way down to the jaw on both sides, which reads as a balaclava with a
       face cut out of it — so the band is full-width only above the fringe and
       thin beside the temples, and stops well above the chin. */
    const cap = inEllipse(x, y, 0.5, 0.435, 0.228, 0.272)
    const face = inEllipse(x, y, 0.5, 0.50, 0.196, 0.235)
    const fringe = t.cut === 3 ? 0.315 : 0.345
    if (cap && (y < fringe || (!face && y < 0.47))) c = hair
    if (t.cut === 1) {
      // long: two rounded masses BEHIND the head, not two rectangles
      if (!onHead && (inEllipse(x, y, 0.302, 0.535, 0.072, 0.235)
                   || inEllipse(x, y, 0.698, 0.535, 0.072, 0.235))) c = hair
    }
    if (t.cut === 2 && inEllipse(x, y, 0.5, 0.185, 0.085, 0.075)) c = hair

    // the face, only where there is a face
    if (onHead) {
      /* a chin, not a lower half: an ellipse low on the face, so the smile and
         the nose still read through it */
      if (t.beard && t.cut !== 1 && inEllipse(x, y, 0.5, 0.635, 0.175, 0.155)) c = shade(hair, 1.08)
      if (y > 0.398 && y < 0.418
          && (Math.abs(x - 0.418) < 0.045 || Math.abs(x - 0.582) < 0.045)) c = shade(hair, 0.9)
      if (inEllipse(x, y, 0.418, 0.458, 0.024, 0.030) || inEllipse(x, y, 0.582, 0.458, 0.024, 0.030)) c = ink
      if (inEllipse(x, y, 0.5, 0.512, 0.018, 0.030)) c = shade(skin, 0.88)
      // the mouth is the gap between two circles, which is a smile
      if (inEllipse(x, y, 0.5, 0.505, 0.075, 0.085) && !inEllipse(x, y, 0.5, 0.487, 0.072, 0.076)
          && y > 0.545) c = shade(skin, 0.55)
    }

    // glasses, over everything they cover
    if (t.glasses) {
      const ring = (cx) => inEllipse(x, y, cx, 0.458, 0.072, 0.062)
                        && !inEllipse(x, y, cx, 0.458, 0.060, 0.050)
      const bridge = y > 0.450 && y < 0.466 && x > 0.472 && x < 0.528
      const arm = y > 0.448 && y < 0.464 && (Math.abs(x - 0.312) < 0.048 || Math.abs(x - 0.688) < 0.048)
      if (ring(0.418) || ring(0.582) || bridge || arm) c = [40, 42, 46]
    }
    return c
  }

  const rgb = Buffer.alloc(size * size * 3)
  const n = SS * SS
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let r = 0, g = 0, b = 0
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const c = paint((px + (sx + 0.5) / SS) / size, (py + (sy + 0.5) / SS) / size)
          r += c[0]; g += c[1]; b += c[2]
        }
      }
      const o = (py * size + px) * 3
      rgb[o] = Math.round(r / n)
      rgb[o + 1] = Math.round(g / n)
      rgb[o + 2] = Math.round(b / n)
    }
  }
  return encodePng(rgb, size, size)
}

function loadEnv() {
  const file = resolve(here, '..', '..', '.env.dev')
  if (!existsSync(file)) return
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const eq = t.indexOf('=')
    if (eq < 1) continue
    const k = t.slice(0, eq).trim()
    const v = t.slice(eq + 1).trim()
    if (v !== '' && process.env[k] === undefined) process.env[k] = v
  }
}
loadEnv()

const raw = process.env.DATABASE_URL
if (!raw) {
  console.error('no connection: set DATABASE_URL (owner) or provide ../.env.dev')
  process.exit(2)
}
const host = raw.slice(raw.lastIndexOf('@') + 1)
const local = /^(localhost|127\.0\.0\.1|\[::1\])[:/]/.test(host)
const db = new pg.Client({
  connectionString: raw,
  ...(local ? {} : { ssl: { rejectUnauthorized: false } }),
})
await db.connect()
console.log(`seed-demo-avatars: ${RESET ? 'RESET' : 'SEED'} against ${host.replace(/:\d+\/.*/, '')}`)

try {
  const people = await db.query(
    `select id, email, display_name, display_name_en, avatar_url
       from echo.app_user
      where org_id = $1 and kind = 'human' and deleted_at is null
      order by email`,
    [ORG],
  )
  if (people.rowCount === 0) throw new Error(`no human members in demo org ${ORG} — seed it first`)

  if (RESET) {
    const r = await db.query(
      `update echo.app_user set avatar_url = null, updated_at = now()
        where org_id = $1 and kind = 'human' and avatar_url is not null`,
      [ORG],
    )
    console.log(`  cleared ${r.rowCount} avatar(s) — back to initials`)
    await db.end()
    process.exit(0)
  }

  let wrote = 0
  let kept = 0
  for (const p of people.rows) {
    const name = p.display_name_en || p.display_name || p.email
    const png = avatarPng(name, p.email, SIZE)
    const url = `data:image/png;base64,${png.toString('base64')}`
    if (url.length > MAX_URL_CHARS) {
      throw new Error(`${p.email}: ${url.length} chars > the API's ${MAX_URL_CHARS} cap — pass a smaller --size`)
    }
    if (p.avatar_url && p.avatar_url !== url && !FORCE) {
      console.log(`  · ${name} — already has a picture, left alone (--force to replace)`)
      kept += 1
      continue
    }
    if (p.avatar_url === url) {
      console.log(`  · ${name} — unchanged`)
      kept += 1
      continue
    }
    await db.query('update echo.app_user set avatar_url = $2, updated_at = now() where id = $1', [p.id, url])
    const look = traits(p.email)
    console.log(`  · ${name} <${p.email}> — cut ${look.cut}${look.glasses ? ', glasses' : ''}${look.beard ? ', beard' : ''}, ${(png.length / 1024).toFixed(1)} KiB`)
    wrote += 1
  }
  console.log(`  ${wrote} written, ${kept} left as they were (${SIZE}×${SIZE} PNG)`)
  console.log('done')
} catch (e) {
  console.error('seed-demo-avatars failed:', e.message)
  process.exitCode = 1
} finally {
  await db.end().catch(() => {})
}
